describe("applyRuleRetroactive", () => {
  it("bulk-updates matching txns and stamps previous_category_slug + retroactive_rule_id", async () => {
    const txA = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}apply-a`,
      merchant: "RETRO-APPLY-1",
      categorySlug: "transferencias",
      daysAgo: 10,
    });
    const txB = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}apply-b`,
      merchant: "RETRO-APPLY-2",
      categorySlug: "suscripciones",
      daysAgo: 30,
    });
    const txSame = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}apply-same`,
      merchant: "RETRO-APPLY-3",
      categorySlug: "alimentacion",
      daysAgo: 5,
    });
    const txOld = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}apply-old`,
      merchant: "RETRO-APPLY-4",
      categorySlug: "transferencias",
      daysAgo: 120,
    });
    const txUnclass = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}apply-unclass`,
      merchant: "RETRO-APPLY-5",
      categorySlug: null,
      daysAgo: 2,
    });

    const ruleId = await seedRule({
      pattern: `%RETRO-APPLY%`,
      categorySlug: "alimentacion",
    });

    const result = await applyRuleRetroactive({ id: ruleId });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.updatedCount).toBe(2);

    const rows = await db.execute<{
      id: number;
      category_slug: string | null;
      previous_category_slug: string | null;
      classification_method: string;
      retroactive_rule_id: number | null;
    }>(sql`
      SELECT id, category_slug, previous_category_slug, classification_method::text, retroactive_rule_id
      FROM transactions
      WHERE id IN (${txA}, ${txB}, ${txSame}, ${txOld}, ${txUnclass})
      ORDER BY id
    `);
    const byId = new Map(rows.map((r) => [r.id, r]));

    expect(byId.get(txA)).toMatchObject({
      category_slug: "alimentacion",
      previous_category_slug: "transferencias",
      classification_method: "rule_retroactive",
      retroactive_rule_id: ruleId,
    });
    expect(byId.get(txB)).toMatchObject({
      category_slug: "alimentacion",
      previous_category_slug: "suscripciones",
      classification_method: "rule_retroactive",
      retroactive_rule_id: ruleId,
    });
    // Already-target: untouched.
    expect(byId.get(txSame)?.category_slug).toBe("alimentacion");
    expect(byId.get(txSame)?.retroactive_rule_id).toBeNull();
    // > 90d: untouched.
    expect(byId.get(txOld)?.category_slug).toBe("transferencias");
    expect(byId.get(txOld)?.retroactive_rule_id).toBeNull();
    // Unclassified: untouched (null != 'alimentacion' is NULL in SQL → filtered out).
    expect(byId.get(txUnclass)?.category_slug).toBeNull();
  });

  it("is idempotent — re-running after apply is a no-op", async () => {
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}idem-a`,
      merchant: "RETRO-IDEM-1",
      categorySlug: "transferencias",
      daysAgo: 3,
    });
    const ruleId = await seedRule({
      pattern: `%RETRO-IDEM%`,
      categorySlug: "alimentacion",
    });

    const first = await applyRuleRetroactive({ id: ruleId });
    expect(first.status).toBe("ok");
    if (first.status !== "ok") throw new Error("expected ok");
    expect(first.updatedCount).toBe(1);

    const second = await applyRuleRetroactive({ id: ruleId });
    expect(second.status).toBe("ok");
    if (second.status !== "ok") throw new Error("expected ok");
    expect(second.updatedCount).toBe(0);
  });

  it("matches description_clean via ILIKE, not just merchant", async () => {
    const tx = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}desc-a`,
      merchant: null,
      descriptionClean: "COMPRA PSE WEB CARULLA-DESC ABC",
      categorySlug: "transferencias",
      daysAgo: 4,
    });
    const ruleId = await seedRule({
      pattern: `%CARULLA-DESC%`,
      categorySlug: "alimentacion",
    });

    const result = await applyRuleRetroactive({ id: ruleId });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.updatedCount).toBe(1);

    const [row] = await db.execute<{ category_slug: string | null }>(sql`
      SELECT category_slug FROM transactions WHERE id = ${tx}
    `);
    expect(row.category_slug).toBe("alimentacion");
  });

  it("returns error when the rule does not belong to the user", async () => {
    const result = await applyRuleRetroactive({ id: 9_999_999 });
    expect(result).toEqual({ status: "error", message: "Regla no encontrada." });
  });
});

describe("revertRuleRetroactive", () => {
  it("restores previous_category_slug and downgrades method to manual", async () => {
    const txA = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}rev-a`,
      merchant: "RETRO-REV-1",
      categorySlug: "transferencias",
      daysAgo: 8,
    });
    const txB = await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}rev-b`,
      merchant: "RETRO-REV-2",
      categorySlug: "suscripciones",
      daysAgo: 40,
    });
    const ruleId = await seedRule({
      pattern: `%RETRO-REV%`,
      categorySlug: "alimentacion",
    });

    const applied = await applyRuleRetroactive({ id: ruleId });
    expect(applied.status).toBe("ok");

    const result = await revertRuleRetroactive({ id: ruleId });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.updatedCount).toBe(2);

    const rows = await db.execute<{
      id: number;
      category_slug: string | null;
      previous_category_slug: string | null;
      classification_method: string;
      retroactive_rule_id: number | null;
    }>(sql`
      SELECT id, category_slug, previous_category_slug, classification_method::text, retroactive_rule_id
      FROM transactions WHERE id IN (${txA}, ${txB}) ORDER BY id
    `);
    const byId = new Map(rows.map((r) => [r.id, r]));

    expect(byId.get(txA)).toMatchObject({
      category_slug: "transferencias",
      previous_category_slug: null,
      classification_method: "manual",
      retroactive_rule_id: null,
    });
    expect(byId.get(txB)).toMatchObject({
      category_slug: "suscripciones",
      previous_category_slug: null,
      classification_method: "manual",
      retroactive_rule_id: null,
    });
  });

  it("is a no-op when no retroactive matches exist for the rule", async () => {
    const ruleId = await seedRule({
      pattern: `%RETRO-REV-NONE%`,
      categorySlug: "alimentacion",
    });
    const result = await revertRuleRetroactive({ id: ruleId });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.updatedCount).toBe(0);
  });

  it("returns error when the rule does not belong to the user", async () => {
    const result = await revertRuleRetroactive({ id: 9_999_999 });
    expect(result).toEqual({ status: "error", message: "Regla no encontrada." });
  });
});
