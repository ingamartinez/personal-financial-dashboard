describe("approveRuleProposal", () => {
  it("creates an auto-generated rule from a pending proposal and marks it approved", async () => {
    const merchant = `${PROPOSAL_PREFIX}CARULLA`;
    const proposalId = await seedProposal({
      merchant,
      categorySlug: "alimentacion",
      correctionTxnIds: [8271, 8342, 8401],
    });

    const result = await approveRuleProposal({ id: proposalId });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.ruleId).toEqual(expect.any(Number));
    expect(result.preview).toBeDefined();

    const [rule] = await db.execute<{
      pattern: string;
      category_slug: string;
      auto_generated: boolean;
      generated_from_corrections: number[] | null;
    }>(sql`
      SELECT pattern, category_slug, auto_generated, generated_from_corrections
      FROM classification_rules
      WHERE user_id = ${TEST_USER_ID} AND pattern = ${`%${merchant}%`}
    `);
    expect(rule.pattern).toBe(`%${merchant}%`);
    expect(rule.category_slug).toBe("alimentacion");
    expect(rule.auto_generated).toBe(true);
    expect(rule.generated_from_corrections).toEqual([8271, 8342, 8401]);

    const [prop] = await db.execute<{ status: string; decided_at: Date | null }>(sql`
      SELECT status::text, decided_at FROM rule_proposals WHERE id = ${proposalId}
    `);
    expect(prop.status).toBe("approved");
    expect(prop.decided_at).not.toBeNull();

    // Cleanup the extra rule we just created.
    await db.execute(sql`
      DELETE FROM classification_rules WHERE pattern = ${`%${merchant}%`}
    `);
  });

  it("refuses to approve a proposal that is already decided", async () => {
    const merchant = `${PROPOSAL_PREFIX}ALREADY`;
    const proposalId = await seedProposal({
      merchant,
      categorySlug: "alimentacion",
      correctionTxnIds: [1, 2, 3],
      status: "approved",
    });

    const result = await approveRuleProposal({ id: proposalId });
    expect(result).toEqual({
      status: "error",
      message: "Esa propuesta ya fue decidida.",
    });
  });

  it("returns error when proposal does not exist", async () => {
    const result = await approveRuleProposal({ id: 9_999_999 });
    expect(result).toEqual({ status: "error", message: "Propuesta no encontrada." });
  });

  it("surfaces a friendly message when approving would create a duplicate rule", async () => {
    const merchant = `${PROPOSAL_PREFIX}DUPE`;
    const proposalId = await seedProposal({
      merchant,
      categorySlug: "alimentacion",
      correctionTxnIds: [1, 2, 3],
    });
    await db.execute(sql`
      INSERT INTO classification_rules (user_id, pattern, category_slug)
      VALUES (${TEST_USER_ID}, ${`%${merchant}%`}, 'alimentacion')
    `);

    const result = await approveRuleProposal({ id: proposalId });
    expect(result.status).toBe("error");
    if (result.status === "error") {
      expect(result.message).toContain("Ya existe una regla");
    }

    // Proposal stays pending — failed approve should not mark as decided.
    const [prop] = await db.execute<{ status: string }>(sql`
      SELECT status::text FROM rule_proposals WHERE id = ${proposalId}
    `);
    expect(prop.status).toBe("pending");
  });
});

