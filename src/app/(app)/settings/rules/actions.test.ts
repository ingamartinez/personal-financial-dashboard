const TEST_USER_ID = 1;
const PATTERN_PREFIX = "TEST-RULES-ACTIONS-";

const PROPOSAL_PREFIX = "TEST-RULES-PROP-";
const TXN_EXTERNAL_PREFIX = "TEST-RULES-TXN-";

async function cleanup() {
  await db.execute(sql`
    DELETE FROM transactions
    WHERE user_id = ${TEST_USER_ID} AND external_id LIKE ${TXN_EXTERNAL_PREFIX + "%"}
  `);
  await db.execute(sql`
    DELETE FROM classification_rules
    WHERE user_id = ${TEST_USER_ID}
      AND (
        pattern LIKE ${PATTERN_PREFIX + "%"}
        OR pattern LIKE ${"%" + PROPOSAL_PREFIX + "%"}
        OR pattern LIKE '%RETRO-%'
        OR pattern LIKE '%CARULLA-PV%'
        OR pattern LIKE '%CARULLA-DESC%'
      )
  `);
  await db.execute(sql`
    DELETE FROM rule_proposals
    WHERE user_id = ${TEST_USER_ID} AND merchant LIKE ${PROPOSAL_PREFIX + "%"}
  `);
}

async function seedTxn(args: {
  externalId: string;
  merchant: string | null;
  descriptionClean?: string;
  categorySlug: string | null;
  daysAgo?: number;
  classificationMethod?: "rule" | "ai" | "manual" | "unclassified";
}): Promise<number> {
  const [acc] = await db.execute<{ id: number }>(sql`
    SELECT id FROM accounts WHERE name = 'Bancolombia Ahorros' LIMIT 1
  `);
  const method = args.classificationMethod ?? (args.categorySlug ? "manual" : "unclassified");
  const rows = await db.execute<{ id: number }>(sql`
    INSERT INTO transactions (
      user_id, account_id, occurred_at, amount_cents, currency,
      description_raw, description_clean, merchant, category_slug,
      classification_method, source, external_id
    ) VALUES (
      ${TEST_USER_ID},
      ${acc.id},
      now() - (interval '1 day' * ${args.daysAgo ?? 0}),
      -5000,
      'COP',
      ${args.descriptionClean ?? args.merchant ?? "test"},
      ${args.descriptionClean ?? null},
      ${args.merchant},
      ${args.categorySlug},
      ${method}::classification_method,
      'sms',
      ${args.externalId}
    )
    RETURNING id
  `);
  return rows[0].id;
}

async function seedProposal(args: {
  merchant: string;
  categorySlug: string;
  correctionTxnIds: number[];
  status?: "pending" | "approved" | "denied";
}): Promise<number> {
  const rows = await db.execute<{ id: number }>(sql`
    INSERT INTO rule_proposals (
      user_id, merchant, category_slug, correction_txn_ids, status
    ) VALUES (
      ${TEST_USER_ID},
      ${args.merchant},
      ${args.categorySlug},
      ${JSON.stringify(args.correctionTxnIds)}::jsonb,
      ${args.status ?? "pending"}::rule_proposal_status
    )
    RETURNING id
  `);
  return rows[0].id;
}

async function seedRule(args: {
  pattern: string;
  categorySlug: string;
  priority?: number;
  active?: boolean;
  autoGenerated?: boolean;
  generatedFromCorrections?: number[] | null;
}): Promise<number> {
  const rows = await db.execute<{ id: number }>(sql`
    INSERT INTO classification_rules (
      user_id, pattern, category_slug, priority, active, auto_generated, generated_from_corrections
    ) VALUES (
      ${TEST_USER_ID},
      ${args.pattern},
      ${args.categorySlug},
      ${args.priority ?? 100},
      ${args.active ?? true},
      ${args.autoGenerated ?? false},
      ${args.generatedFromCorrections ? JSON.stringify(args.generatedFromCorrections) : null}::jsonb
    )
    RETURNING id
  `);
  return rows[0].id;
}

beforeEach(cleanup);
afterEach(cleanup);

describe("createRule", () => {
  it("creates a rule with auto_generated=false by default and returns a preview", async () => {
    const result = await createRule({
      pattern: `${PATTERN_PREFIX}%CARULLA%`,
      categorySlug: "alimentacion",
      priority: 120,
    });

    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.ruleId).toEqual(expect.any(Number));
    expect(result.preview.matchCount).toBe(0);
    expect(result.preview.sample).toEqual([]);

    const rows = await db.execute<{
      pattern: string;
      category_slug: string;
      priority: number;
      active: boolean;
      auto_generated: boolean;
    }>(sql`
      SELECT pattern, category_slug, priority, active, auto_generated
      FROM classification_rules
      WHERE user_id = ${TEST_USER_ID} AND pattern = ${PATTERN_PREFIX + "%CARULLA%"}
    `);
    expect(rows).toHaveLength(1);
    expect(rows[0].category_slug).toBe("alimentacion");
    expect(rows[0].priority).toBe(120);
    expect(rows[0].active).toBe(true);
    expect(rows[0].auto_generated).toBe(false);
  });

  it("preview counts only txns from last 90d that match and have a different category", async () => {
    // Three matching merchants, different current categories — should be 3 matches.
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-a`,
      merchant: "CARULLA-PV-1",
      categorySlug: "transferencias",
      daysAgo: 5,
    });
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-b`,
      merchant: "CARULLA-PV-2",
      categorySlug: "suscripciones",
      daysAgo: 20,
    });
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-c`,
      merchant: "CARULLA-PV-3",
      categorySlug: "salud",
      daysAgo: 80,
    });
    // Excluded: already in target category.
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-excl-same`,
      merchant: "CARULLA-PV-4",
      categorySlug: "alimentacion",
      daysAgo: 10,
    });
    // Excluded: > 90d ago.
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-excl-old`,
      merchant: "CARULLA-PV-5",
      categorySlug: "transferencias",
      daysAgo: 120,
    });
    // Excluded: unclassified (null).
    await seedTxn({
      externalId: `${TXN_EXTERNAL_PREFIX}pv-excl-null`,
      merchant: "CARULLA-PV-6",
      categorySlug: null,
      daysAgo: 3,
    });

    const result = await createRule({
      pattern: `%CARULLA-PV%`,
      categorySlug: "alimentacion",
      priority: 100,
    });

    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("expected ok");
    expect(result.preview.matchCount).toBe(3);
    expect(result.preview.sample).toHaveLength(3);
    // Sample order: newest first.
    expect(result.preview.sample[0].merchant).toBe("CARULLA-PV-1");
    expect(result.preview.sample[0].currentCategorySlug).toBe("transferencias");
    // Cleanup the rule we created (our rule PATTERN doesn't match the prefix).
    await db.execute(sql`
      DELETE FROM classification_rules WHERE user_id = ${TEST_USER_ID} AND pattern = ${"%CARULLA-PV%"}
    `);
  });

  it("rejects when category does not exist for the user", async () => {
    const result = await createRule({
      pattern: `${PATTERN_PREFIX}%X%`,
      categorySlug: "no-existe",
      priority: 100,
    });
    expect(result).toEqual({
      status: "error",
      message: "La categoría no existe o está archivada.",
    });
  });

  it("rejects duplicate (pattern, category) with a clear message", async () => {
    await seedRule({
      pattern: `${PATTERN_PREFIX}%DUP%`,
      categorySlug: "alimentacion",
    });
    const result = await createRule({
      pattern: `${PATTERN_PREFIX}%DUP%`,
      categorySlug: "alimentacion",
    });
    expect(result).toEqual({
      status: "error",
      message: "Ya tenés una regla con ese patrón y categoría.",
    });
  });

  it("rejects empty pattern via zod", async () => {
    const result = await createRule({
      pattern: "",
      categorySlug: "alimentacion",
    });
    expect(result.status).toBe("error");
  });
});

describe("updateRule", () => {
  it("updates pattern, category, priority on an existing rule", async () => {
    const id = await seedRule({
      pattern: `${PATTERN_PREFIX}%OLD%`,
      categorySlug: "alimentacion",
      priority: 100,
    });

    const result = await updateRule({
      id,
      pattern: `${PATTERN_PREFIX}%NEW%`,
      categorySlug: "transferencias",
      priority: 50,
    });

    expect(result).toEqual({ status: "ok" });
    const rows = await db.execute<{
      pattern: string;
      category_slug: string;
      priority: number;
    }>(sql`
      SELECT pattern, category_slug, priority
      FROM classification_rules WHERE id = ${id}
    `);
    expect(rows[0].pattern).toBe(`${PATTERN_PREFIX}%NEW%`);
    expect(rows[0].category_slug).toBe("transferencias");
    expect(rows[0].priority).toBe(50);
  });

  it("returns error when rule belongs to a different user", async () => {
    const result = await updateRule({
      id: 9_999_999,
      pattern: `${PATTERN_PREFIX}%X%`,
      categorySlug: "alimentacion",
      priority: 100,
    });
    expect(result).toEqual({ status: "error", message: "Regla no encontrada." });
  });
});

describe("toggleRuleActive", () => {
  it("flips active from true to false and back", async () => {
    const id = await seedRule({
      pattern: `${PATTERN_PREFIX}%TOGGLE%`,
      categorySlug: "alimentacion",
      active: true,
    });

    const off = await toggleRuleActive({ id, active: false });
    expect(off).toEqual({ status: "ok" });

    const [rowOff] = await db.execute<{ active: boolean }>(sql`
      SELECT active FROM classification_rules WHERE id = ${id}
    `);
    expect(rowOff.active).toBe(false);

    const on = await toggleRuleActive({ id, active: true });
    expect(on).toEqual({ status: "ok" });
    const [rowOn] = await db.execute<{ active: boolean }>(sql`
      SELECT active FROM classification_rules WHERE id = ${id}
    `);
    expect(rowOn.active).toBe(true);
  });
});

